import re

"""
정규식 패턴 모음.

문서 구조와 메타데이터 추출에 사용하는 모든 정규식을
한 곳에서 관리한다.
"""

PATTERNS = {
    "사업기간": (
        r"(?:[□■▪▶○◦•]?\s*(?:\d+[\.\)]\s*)?)"
        r"(?:사업\s*기간|사업기간|수행\s*기간|용역기간|계약기간|과업기간)"
    ),
    "참가자격": (
        r"(?:[□■▪▶○◦•]?\s*(?:\d+[\.\)]\s*)?)"
        r"(?:입찰\s*참가\s*자격|참가자격|신청자격|지원자격|응모자격)"
    ),
    "보안특약": r"□[^가-힣]{0,10}보안\s*특약",
    "하자보수": r"□[^가-힣]{0,10}하자\s*보수",
}

HEADER_PATTERNS = {
    "Ⅰ.": r"^\s*[ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ]+\.",
    "1.": r"^\s*\d+\.",
    "1)": r"^\s*\d+\)",
    "가.": r"^\s*[가-힣]\.",
    "□": r"^\s*□",
    "■": r"^\s*■",
    "○": r"^\s*[○◦•▪▶]",
}

METADATA_VARIANTS = {
    "사업기간": [
        r"사업\s*기간",
        r"사업기간",
        r"사업\s*수행\s*기간",
        r"수행\s*기간",
        r"용역\s*기간",
        r"계약\s*기간",
        r"과업\s*기간",
    ],
    "참가자격": [
        r"입찰\s*참가\s*자격",
        r"참가\s*자격",
        r"참가자격",
        r"신청\s*자격",
        r"지원\s*자격",
        r"응모\s*자격",
        r"자격\s*요건",
        r"참가\s*요건",
    ],
}

STRUCTURE_PATTERNS = {
    "□": r"□",
    "■": r"■",
    "○": r"○",
    "◦": r"◦",
    "●": r"●",
    "※": r"※",
    "숫자_점": r"(?m)^\s*\d+\.",
    "숫자_괄호": r"(?m)^\s*\d+\)",
    "한글_점": r"(?m)^\s*[가-힣]\.",
    "한글_괄호": r"(?m)^\s*[가-힣]\)",
    "로마숫자": r"(?m)^\s*[ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ]+\.",
    "괄호숫자": r"(?m)^\s*\(\d+\)",
}


# 연속 공백/탭 (5칸 이상)
PATTERN_LONG_SPACE = re.compile(r"[ \t]{5,}")

# 연속 줄바꿈 (4개 이상)
PATTERN_LONG_NEWLINE = re.compile(r"\n{4,}")

# 개인정보/자리표시자용 마스킹 문자
PATTERN_PLACEHOLDER = re.compile(r"[ㅇ○]{2,}")

# 빈 괄호 또는 공백만 있는 괄호  예: "( )", "(   )"
PATTERN_EMPTY_PAREN = re.compile(r"\(\s*\)")

# 페이지번호 형태  예: "- 12 -", "12 / 100"
PATTERN_PAGE_NUMBER = re.compile(r"^\s*-?\s*\d+\s*(-|/\s*\d+)?\s*-?\s*$")

# 서명/날인 흔적
PATTERN_SIGNATURE = re.compile(r"\(\s*인\s*\)")

# 밑줄/점선 등 구분선  예: "________", "………", "----------"
PATTERN_DIVIDER_LINE = re.compile(r"^[_\-—=~・.…\s]{5,}$")
